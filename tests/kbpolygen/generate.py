"""Emit kernel/util/kbpoly_data.h, the polynomial Kaiser-Bessel degree table.

    uv run --with mpmath==1.3.0 python -m tests.kbpolygen.generate

The degree for (sigma, m, reach, format) is the smallest d whose Chebyshev
truncation, 2 sum_{j>d} max_cells |c_j| / peak, is within
max(0.05 pi e^(-b R), eps). The coefficients are exact (mpmath), so the table
carries none of the rounding noise a plan-time fit would see.
"""
import argparse
import math
import sys
from multiprocessing import Pool

import mpmath as mp

# MANT_DIG -> unit roundoff of the format; eps = 2 u.
FORMATS = (24, 64, 113, 53)
NC = 44                  # Chebyshev points per cell; far past every degree used
SIG_LO, SIG_HI = 1.1, 4.0
GRID = 291               # sigma step 0.01
BISECT = 7               # 0.01 / 2^7 < 1e-4
C_MAX = 2.81             # largest c in E = c / I0(2 pi R sqrt(1 - 1/sigma))

HEADER = """\
/* Generated by tests/kbpolygen/generate.py; do not edit.
 *
 * Degree of the polynomial Kaiser-Bessel window, reach m + 1, sigma in
 * [1.1, 4]. kb_poly_tab_deg0[m] is the degree at sigma 1.1; it rises by one
 * from each sigma kb_poly_tab_brk[k] / 1e4 on, k from kb_poly_tab_off[m] to
 * kb_poly_tab_off[m + 1]. Rows stop at the largest
 * m_opt = ceil(KB_POLY_BR_OPT / b) - 1, b = pi (2 - 1/sigma), past which the
 * transform error no longer falls and the degree no longer rises. */
"""


def br_opt(mant):
    """b R where the truncation error c / I0(a R) meets the round-off floor
    u I0(b R) / I0(a R), from I0(x) ~ e^x / sqrt(2 pi x)."""
    L = math.log(C_MAX / 2.0 ** -mant)
    return L + 0.5 * math.log(2 * math.pi * L)


def m_opt(sigma, mant):
    b = math.pi * (2 - 1 / sigma)
    return max(1, math.ceil(br_opt(mant) / b - 1))


def sigma_at(i):
    return SIG_LO + i / 100


_X = _CM = None


def _init():
    global _X, _CM
    mp.mp.dps = 50
    _X = [(mp.cos(mp.pi * (k + mp.mpf(1) / 2) / NC) + 1) / 2 for k in range(NC)]
    _CM = [[mp.cos(mp.pi * j * (k + mp.mpf(1) / 2) / NC) for k in range(NC)]
           for j in range(NC)]


def degrees(sigma, m):
    """{MANT_DIG: degree} at one sigma."""
    R = m + 1
    b = mp.pi * (2 - 1 / mp.mpf(sigma))

    def phi(nu):
        z = R * R - nu * nu
        if z > 0:
            s = mp.sqrt(z)
            return mp.sinh(b * s) / (mp.pi * s)
        if z < 0:
            s = mp.sqrt(-z)
            return mp.sin(b * s) / (mp.pi * s)
        return b / mp.pi

    env = [mp.mpf(0)] * NC
    # The 2m + 4 cells of KB_POLY_COLS(m).
    for a in range(-(m + 2), m + 2):
        v = [phi(a + t) for t in _X]
        for j in range(NC):
            c = abs(2 * mp.fsum(v[k] * _CM[j][k] for k in range(NC)) / NC)
            env[j] = max(env[j], c)
    tail = [mp.mpf(0)] * NC
    for j in range(NC - 2, -1, -1):
        tail[j] = tail[j + 1] + env[j + 1]
    peak = phi(0)
    tol = mp.mpf("0.05") * mp.pi * mp.exp(-b * R)
    out = {}
    for mant in FORMATS:
        t = max(tol, mp.mpf(2) ** (1 - mant)) * peak
        out[mant] = next(d for d in range(NC - 1) if 2 * tail[d] <= t)
    return out


def row(args):
    """Degree at sigma 1.1 and the rising thresholds of row m, per format,
    over the sigma range where some format reads row m."""
    m, mants = args
    last = max(i for i in range(GRID)
               if any(m_opt(sigma_at(i), p) >= m for p in mants))
    last = min(GRID - 1, last + 1)
    vals = [degrees(sigma_at(i), m) for i in range(last + 1)]
    steps = {p: [] for p in mants}
    for p in mants:
        for i in range(last):
            step = vals[i + 1][p] - vals[i][p]
            if step == 0:
                continue
            if step != 1:
                raise SystemExit("m=%d MANT_DIG=%d: degree steps by %d at sigma %.2f"
                                 % (m, p, step, sigma_at(i)))
            lo, hi = mp.mpf(sigma_at(i)), mp.mpf(sigma_at(i + 1))
            for _ in range(BISECT):
                mid = (lo + hi) / 2
                if degrees(mid, m)[p] == vals[i][p]:
                    lo = mid
                else:
                    hi = mid
            # Rounded down, to the side of the higher degree.
            steps[p].append(math.floor(lo * 10**4))
    return m, {p: vals[0][p] for p in mants}, steps


def emit(mant, mmax, d0, steps, first):
    out = ["#if MANT_DIG == %d" % mant if first else
           ("#elif MANT_DIG == %d" % mant if mant != 53 else "#else")]
    out.append("  #define KB_POLY_TAB_MMAX %d" % mmax)
    out.append("  #define KB_POLY_BR_OPT K(%.6f)" % br_opt(mant))
    out.append("  static const unsigned char kb_poly_tab_deg0[%d] = {" % (mmax + 1))
    out.append("    " + ", ".join(str(d0.get(m, 0)) for m in range(mmax + 1)) + ",")
    out.append("  };")
    flat, off = [], []
    for m in range(mmax + 1):
        off.append(len(flat))
        # Row m is read only where m_opt >= m; later thresholds never apply.
        flat += [t for t in steps.get(m, []) if m_opt(t / 1e4 - 0.01, mant) >= m]
    off.append(len(flat))
    out.append("  static const short kb_poly_tab_off[%d] = {" % (mmax + 2))
    out.append("    " + ", ".join(map(str, off)) + ",")
    out.append("  };")
    out.append("  static const unsigned short kb_poly_tab_brk[%d] = {" % max(len(flat), 1))
    vals = [str(t) for t in flat] or ["0"]
    out += ["    " + ", ".join(vals[k:k + 12]) + "," for k in range(0, len(vals), 12)]
    out.append("  };")
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="kernel/util/kbpoly_data.h")
    ap.add_argument("--jobs", type=int, default=None)
    args = ap.parse_args(argv)

    mmax = {p: m_opt(SIG_LO, p) for p in FORMATS}
    jobs = [(m, [p for p in FORMATS if mmax[p] >= m])
            for m in range(max(mmax.values()), 0, -1)]
    d0, steps = {p: {} for p in FORMATS}, {p: {} for p in FORMATS}
    with Pool(args.jobs, initializer=_init) as pool:
        for m, r0, rs in pool.imap_unordered(row, jobs):
            sys.stderr.write("m=%d\n" % m)
            for p in r0:
                d0[p][m] = r0[p]
                steps[p][m] = rs[p]

    out = [HEADER]
    for i, p in enumerate(FORMATS):
        out += emit(p, mmax[p], d0[p], steps[p], i == 0)
    out.append("#endif")
    with open(args.out, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
