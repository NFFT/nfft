#define ERR(x,y) IF(ABS(x - y) == K(0.0), ABS(x - y), ABS(x - y) / ABS(y))

/* Both forms are exp-free in the branch that carries their own coefficient
 * table, so the flat bound applies there and is what actually constrains the
 * fit. Worst measured across all four formats: 1.43 ulp for exp_scaled above
 * the split, 0.89 for logtail above it. */
static const R bound_multiplier = K(4.0);

/* Below its split exp_scaled carries EXP(-x), and a target that reduces the
 * argument of EXP in one rounding gives up 0.5 * eps * x there. Worst measured
 * 4.65 ulp, at MANT_DIG 64 with such an EXP. */
#define I0E_SMALL_BOUND (K(2.0) * bound_multiplier * eps)

/* Below its split logtail subtracts x from a logarithm of the same size and
 * gives up a little over three bits. Worst measured 2.55 ulp, at MANT_DIG 113. */
#define LOGTAIL_SMALL_BOUND (K(4.0) * bound_multiplier * eps)

void X(check_bessel_i0_exp_scaled)(void)
{
  const R eps = Y(float_property)(NFFT_EPSILON);
  unsigned int j;

  printf("BESSEL I0 EXP SCALED\n--------------------\n");

  for (j = 0; j < sizeof(i0e_r) / sizeof(i0e_r[0]); j++)
  {
    const R x = (R)j;
    const R y = Y(bessel_i0_exp_scaled)(x);
    const R err = ERR(y, i0e_r[j]);
    const R b = IF(x > I0_ABOVE_EVERY_SPLIT, bound_multiplier * eps,
        I0E_SMALL_BOUND);
    const int ok = IF(err < b, 1, 0);

    printf("i0e[" __FE__ "] = " __FE__ " err_rel = " __FE__ " %-2s " __FE__
      " -> %-4s\n", x, y, err, IF(ok == 0, ">=", "<"), b,
      IF(ok == 0, "FAIL", "OK"));
    CU_ASSERT(ok == 1);
  }
}

void X(check_bessel_i0_logtail)(void)
{
  const R eps = Y(float_property)(NFFT_EPSILON);
  unsigned int j;

  printf("BESSEL I0 LOGTAIL\n-----------------\n");

  for (j = 0; j < sizeof(logtail_r) / sizeof(logtail_r[0]); j++)
  {
    const R x = (R)j;
    const R y = Y(bessel_i0_logtail)(x);
    const R err = ERR(y, logtail_r[j]);
    const R b = IF(x > I0_ABOVE_EVERY_SPLIT, bound_multiplier * eps,
        LOGTAIL_SMALL_BOUND);
    const int ok = IF(err < b, 1, 0);

    printf("i0_logtail[" __FE__ "] = " __FE__ " err_rel = " __FE__ " %-2s "
      __FE__ " -> %-4s\n", x, y, err, IF(ok == 0, ">=", "<"), b,
      IF(ok == 0, "FAIL", "OK"));
    CU_ASSERT(ok == 1);
  }
}
