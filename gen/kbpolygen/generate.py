"""Emit kernel/util/kbpoly_data.h, the polynomial Kaiser-Bessel degree table.

    uv run --with mpmath==1.3.0 --with numpy python -m gen.kbpolygen.generate

The table holds h = degree / 2 per (sigma, m, format): the smallest h whose
interpolation error adds at most 5% of the transform's own error, measured
through the transform's error functional (functional.py) rather than bounded
by the Chebyshev tail. The error coefficients are exact (mpmath); only the
functional's sum, which cancels nothing, runs in double.
"""
import argparse
import math
import sys
from multiprocessing import Pool

import mpmath as mp

from gen.kbpolygen import functional

# MANT_DIG -> unit roundoff of the format; eps = 2 u.
FORMATS = (24, 64, 113, 53)
NC = 44                  # Chebyshev points per cell; far past every degree used
SIG_LO, SIG_HI = 1.1, 4.0
GRID = 291               # sigma step 0.01
BISECT = 7               # 0.01 / 2^7 < 1e-4
C_MAX = 2.81             # largest c in E = c / I0(2 pi R sqrt(1 - 1/sigma))
C_MIN = 1.10             # smallest c, certified over sigma 1.1 .. 4
K_LS = 30                # the correction pays while E >= K_LS * eps

HEADER = """\
/* Generated by gen/kbpolygen/generate.py; do not edit.
 *
 * Half degree h of the polynomial Kaiser-Bessel window per format, m and
 * sigma in [1.1, 4], read by Y(kb_poly_degree), which returns 2 h. h is the
 * lowest at which the interpolation error contributes at most 5% of the
 * transform's own error c / I0(2 pi R sqrt(1 - 1/sigma)), c = 1.10, measured
 * through the transform's error functional, or at most eps; see
 * gen/kbpolygen/README.md.
 *
 * Per format:
 *   kb_poly_tab_h0[m]     h at sigma 1.1.
 *   kb_poly_tab_brk[k]    sigma times 1e4, rounded down. From each such sigma
 *                         on, h is one higher. Row m uses k from
 *                         kb_poly_tab_off[m] to kb_poly_tab_off[m + 1] - 1.
 *   KB_POLY_TAB_MMAX      last row, the m_opt of sigma 1.1.
 *
 * A plan reads row min(m, m_opt), m_opt = ceil(KB_POLY_BR_OPT / b) - 1,
 * b = pi (2 - 1/sigma). Past m_opt the transform error no longer falls, so
 * the degree does not rise.
 *
 * KB_POLY_BR_LS_<mant>: b R up to which the plan-time correction of
 * Y(kb_poly_correct) pays in a type of that mantissa width: the truncation
 * error c / I0(a R), c = 1.10, is still K_LS = 30 times the round-off floor
 * u I0(b R) / I0(a R). The m_opt rule above with that margin. */
"""


def br_opt(mant):
    """b R where the truncation error c / I0(a R) meets the round-off floor
    u I0(b R) / I0(a R), from I0(x) ~ e^x / sqrt(2 pi x)."""
    L = math.log(C_MAX / 2.0 ** -mant)
    return L + 0.5 * math.log(2 * math.pi * L)


def br_ls(mant):
    """b R up to which the correction pays: the truncation error c / I0(a R),
    c = C_MIN, is still K_LS times the round-off floor u I0(b R) / I0(a R),
    i.e. I0(b R) <= c / (K_LS u); the m_opt derivation with a margin."""
    L = math.log(C_MIN / (K_LS * 2.0 ** -mant))
    return L + 0.5 * math.log(2 * math.pi * L)


def m_opt(sigma, mant):
    b = math.pi * (2 - 1 / sigma)
    return max(1, math.ceil(br_opt(mant) / b - 1))


def sigma_at(i):
    return SIG_LO + i / 100


_S = _CM = None


def _init():
    global _S, _CM
    mp.mp.dps = 50
    # Offsets from the cell centre and the cosines of the NC-point
    # first-kind Chebyshev transform, as kbpoly.c lays its nodes.
    _S = [mp.cos(mp.pi * (k + mp.mpf(1) / 2) / NC) / 2 for k in range(NC)]
    _CM = [[mp.cos(mp.pi * j * (k + mp.mpf(1) / 2) / NC) for k in range(NC)]
           for j in range(NC)]


def window(sigma, m):
    """phi(nu) / I0(R b) with reach R = m + 1, both branches, and b."""
    R = m + 1
    b = mp.pi * (2 - 1 / mp.mpf(sigma))
    peak = mp.besseli(0, R * b)

    def phi(nu):
        z = R * R - nu * nu
        if z > 0:
            s = mp.sqrt(z)
            return mp.sinh(b * s) / (mp.pi * s) / peak
        if z < 0:
            s = mp.sqrt(-z)
            return mp.sin(b * s) / (mp.pi * s) / peak
        return b / mp.pi / peak

    return phi, b


def cheb_coef(vals):
    """NC Chebyshev coefficients of the values at the nodes _S."""
    return [2 * mp.fsum(vals[k] * _CM[j][k] for k in range(NC)) / NC
            * (mp.mpf(1) / 2 if j == 0 else 1) for j in range(NC)]


def interp_error(coef, h):
    """Coefficients of phi - p_{2h}, p the interpolant on 2h + 1 first-kind
    nodes, from the exact series coef (NC terms). All in mpmath, so the small
    numbers come out exact."""
    n = 2 * h + 1
    th = [mp.pi * (i + mp.mpf(1) / 2) / n for i in range(n)]
    vals = [mp.fsum(coef[k] * mp.cos(k * th[i]) for k in range(NC)) for i in range(n)]
    err = list(coef)
    for k in range(n):
        ck = 2 * mp.fsum(vals[i] * mp.cos(k * th[i]) for i in range(n)) / n
        if k == 0:
            ck /= 2
        err[k] = coef[k] - ck
    return err


def phi_hut(sigma, m, xi):
    """I0(R sqrt(b^2 - (2 pi xi)^2)) / I0(R b), the library's PHI_HUT."""
    R = m + 1
    b = mp.pi * (2 - 1 / mp.mpf(sigma))
    out = []
    for x in xi:
        w = 2 * mp.pi * mp.mpf(x)
        out.append(float(mp.besseli(0, R * mp.sqrt(b * b - w * w)) / mp.besseli(0, R * b)))
    return out


def halves(sigma, m, start=None):
    """{MANT_DIG: h} at one sigma. start, {MANT_DIG: h}, is a guess from a
    nearby sigma; the search goes up from one below it and then back down,
    so the answer is the smallest h either way."""
    R = m + 1
    phi, b = window(sigma, m)
    a = 2 * mp.pi * mp.sqrt(1 - 1 / mp.mpf(sigma))
    alias = C_MIN / mp.besseli(0, a * R)
    xi, _ = functional.grid(float(sigma))
    C = phi_hut(sigma, m, xi)
    coefs = [cheb_coef([phi(j + mp.mpf(1) / 2 + s) for s in _S]) for j in range(m + 1)]
    tol = {p: float(max(mp.mpf("0.05") * alias, mp.mpf(2) ** (1 - p))) for p in FORMATS}
    cache = {}

    def part(h):
        if h not in cache:
            err = [[float(v) for v in interp_error(c, h)] for c in coefs]
            cache[h] = functional.poly_part(err, C, float(sigma), m)
        return cache[h]

    out = {}
    for p in FORMATS:
        h = max(1, (start or {}).get(p, 2) - 1)
        while h < NC // 2 and part(h) > tol[p]:
            h += 1
        if h >= NC // 2:
            raise SystemExit("sigma=%g m=%d: no h below %d" % (sigma, m, NC // 2))
        while h > 1 and part(h - 1) <= tol[p]:
            h -= 1
        out[p] = h
    return out


def row(args):
    """h at sigma 1.1 and the rising thresholds of row m, per format, over
    the sigma range where some format reads row m."""
    m, mants = args
    last = max(i for i in range(GRID)
               if any(m_opt(sigma_at(i), p) >= m for p in mants))
    last = min(GRID - 1, last + 1)
    vals, prev = [], None
    for i in range(last + 1):
        prev = halves(sigma_at(i), m, prev)
        vals.append(dict(prev))
    # The table is monotone in sigma; where the measured h falls (a wider
    # band is cheaper to meet than a narrower window is costly), keep the
    # running maximum, which is never below the exact h.
    for p in mants:
        for i in range(1, last + 1):
            vals[i][p] = max(vals[i][p], vals[i - 1][p])
    steps = {p: [] for p in mants}
    for p in mants:
        for i in range(last):
            step = vals[i + 1][p] - vals[i][p]
            if step <= 0:
                continue
            lo, hi = mp.mpf(sigma_at(i)), mp.mpf(sigma_at(i + 1))
            for _ in range(BISECT):
                mid = (lo + hi) / 2
                if halves(mid, m, vals[i])[p] <= vals[i][p]:
                    lo = mid
                else:
                    hi = mid
            # Rounded down, to the side of the higher h; a step of two puts
            # the threshold twice.
            steps[p] += [math.floor(lo * 10**4)] * step
    return m, {p: vals[0][p] for p in mants}, steps


def emit(mant, mmax, h0, steps, first):
    out = ["#if MANT_DIG == %d" % mant if first else
           ("#elif MANT_DIG == %d" % mant if mant != 53 else "#else")]
    out.append("  #define KB_POLY_TAB_MMAX %d" % mmax)
    out.append("  #define KB_POLY_BR_OPT K(%.6f)" % br_opt(mant))
    out.append("  static const unsigned char kb_poly_tab_h0[%d] = {" % (mmax + 1))
    out.append("    " + ", ".join(str(h0.get(m, 0)) for m in range(mmax + 1)) + ",")
    out.append("  };")
    flat, off = [], []
    for m in range(mmax + 1):
        off.append(len(flat))
        # Row m is read only where m_opt >= m; later thresholds never apply.
        flat += [t for t in steps.get(m, []) if m_opt(t / 1e4 - 0.01, mant) >= m]
    off.append(len(flat))
    out.append("  static const short kb_poly_tab_off[%d] = {" % (mmax + 2))
    out.append("    " + ", ".join(map(str, off)) + ",")
    out.append("  };")
    out.append("  static const unsigned short kb_poly_tab_brk[%d] = {" % max(len(flat), 1))
    vals = [str(t) for t in flat] or ["0"]
    out += ["    " + ", ".join(vals[k:k + 12]) + "," for k in range(0, len(vals), 12)]
    out.append("  };")
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="kernel/util/kbpoly_data.h")
    ap.add_argument("--jobs", type=int, default=None)
    ap.add_argument("--constants-only", action="store_true",
                    help="rewrite only the header comment and the KB_POLY_BR_LS "
                         "constants of an existing table")
    args = ap.parse_args(argv)

    if args.constants_only:
        body = open(args.out).read()
        body = body[body.index("#if MANT_DIG"):]
        out = [HEADER]
        for p in sorted(FORMATS):
            out.append("#define KB_POLY_BR_LS_%d K(%.6f)" % (p, br_ls(p)))
        out.append("")
        with open(args.out, "w") as f:
            f.write("\n".join(out) + "\n" + body)
        return

    mmax = {p: m_opt(SIG_LO, p) for p in FORMATS}
    jobs = [(m, [p for p in FORMATS if mmax[p] >= m])
            for m in range(max(mmax.values()), 0, -1)]
    h0, steps = {p: {} for p in FORMATS}, {p: {} for p in FORMATS}
    with Pool(args.jobs, initializer=_init) as pool:
        for m, r0, rs in pool.imap_unordered(row, jobs):
            sys.stderr.write("m=%d\n" % m)
            for p in r0:
                h0[p][m] = r0[p]
                steps[p][m] = rs[p]

    out = [HEADER]
    for p in sorted(FORMATS):
        out.append("#define KB_POLY_BR_LS_%d K(%.6f)" % (p, br_ls(p)))
    out.append("")
    for i, p in enumerate(FORMATS):
        out += emit(p, mmax[p], h0[p], steps[p], i == 0)
    out.append("#endif")
    with open(args.out, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
