"""Emit kernel/util/sincpowpoly_data.h, the polynomial sinc-power degree table.

    uv run --with mpmath==1.3.0 python -m gen.sincpowpolygen.generate

The degree for (sigma, m, format) is the smallest d whose Chebyshev
truncation, 2 sum_{j>d} max_cells |c_j| / peak, is within eps. The
coefficients are exact (mpmath), so the table carries none of the rounding
noise a plan-time fit would see.
"""

import argparse
import math
import sys
from multiprocessing import Pool

import mpmath as mp

# MANT_DIG of each format; eps = 2^(1 - MANT_DIG).
FORMATS = (24, 64, 113, 53)
NC = 48  # Chebyshev points per cell; far past every degree used
SIG_LO = 1.1
GRID = 291  # sigma step 0.01 up to 4
BISECT = 7  # 0.01 / 2^7 < 1e-4
MMAX = 32  # last row; larger m read it
M_CHECK = 64  # row that must not need more than row MMAX

HEADER = """\
/* Generated by gen/sincpowpolygen/generate.py; do not edit.
 *
 * Polynomial degree of the sinc-power window per format, m and sigma in
 * [1.1, 4], read by Y(sincpow_poly_degree). The degree is the lowest at which
 * the Chebyshev truncation of the window stays below eps of the peak;
 * gen/sincpowpolygen/README.md has the rule.
 *
 * Per format:
 *   sp_poly_tab_deg0[m]   degree at sigma 1.1.
 *   sp_poly_tab_brk[k]    sigma times 1e4, rounded down. From each such sigma
 *                         on, the degree is one higher. Row m uses k from
 *                         sp_poly_tab_off[m] to sp_poly_tab_off[m + 1] - 1.
 *   SP_POLY_TAB_MMAX      last row. A plan with larger m reads it: the
 *                         degree does not rise with m.
 *
 * The plan rounds an odd degree up. */
"""


def sigma_at(i):
    return SIG_LO + i / 100


_X = _CM = None


def _init():
    global _X, _CM
    mp.mp.dps = 50
    _X = [mp.cos(mp.pi * (k + mp.mpf(1) / 2) / NC) / 2 for k in range(NC)]
    _CM = [
        [mp.cos(mp.pi * j * (k + mp.mpf(1) / 2) / NC) for k in range(NC)]
        for j in range(NC)
    ]


def degrees(sigma, m):
    """{MANT_DIG: degree} at one sigma."""
    sigma = mp.mpf(sigma)
    w = (2 * sigma - 1) / (2 * m * sigma)

    def phi(nu):
        a = mp.pi * w * nu
        return w * (mp.sin(a) / a) ** (2 * m) if a != 0 else w

    env = [mp.mpf(0)] * NC
    # The m + 2 cells [m + 1 - c, m + 2 - c) of |nu|, CELL_POLY_COLS(m).
    for c in range(m + 2):
        ctr = mp.mpf(m + 1 - c) + mp.mpf(1) / 2
        v = [phi(ctr + t) for t in _X]
        for j in range(NC):
            s = abs(2 * mp.fsum(v[k] * _CM[j][k] for k in range(NC)) / NC)
            env[j] = max(env[j], s)
    tail = [mp.mpf(0)] * NC
    for j in range(NC - 2, -1, -1):
        tail[j] = tail[j + 1] + env[j + 1]
    return {
        p: next(d for d in range(NC - 1) if 2 * tail[d] <= mp.mpf(2) ** (1 - p) * w)
        for p in FORMATS
    }


def rows(vals):
    return [
        "    " + ", ".join(map(str, vals[k : k + 12])) + ","
        for k in range(0, len(vals), 12)
    ]


def emit(mant, d0, steps, first):
    out = [
        f"#if MANT_DIG == {mant}"
        if first
        else (f"#elif MANT_DIG == {mant}" if mant != 53 else "#else")
    ]
    out.append(f"  #define SP_POLY_TAB_MMAX {MMAX}")
    out.append(f"  static const unsigned char sp_poly_tab_deg0[{MMAX + 1}] = {{")
    out += rows([d0.get(m, 0) for m in range(MMAX + 1)])
    out.append("  };")
    flat, off = [], []
    for m in range(MMAX + 1):
        off.append(len(flat))
        flat += steps.get(m, [])
    off.append(len(flat))
    out.append(f"  static const short sp_poly_tab_off[{MMAX + 2}] = {{")
    out += rows(off)
    out.append("  };")
    out.append(
        f"  static const unsigned short sp_poly_tab_brk[{max(len(flat), 1)}] = {{"
    )
    out += rows(flat or [0])
    out.append("  };")
    return out


def thresholds(m, vals):
    """Bisected thresholds of row m from its grid values."""
    steps = {p: [] for p in FORMATS}
    for p in FORMATS:
        for i in range(GRID - 1):
            if vals[i + 1][p] == vals[i][p]:
                continue
            lo, hi = mp.mpf(sigma_at(i)), mp.mpf(sigma_at(i + 1))
            for _ in range(BISECT):
                mid = (lo + hi) / 2
                if degrees(mid, m)[p] <= vals[i][p]:
                    lo = mid
                else:
                    hi = mid
            steps[p].append(math.floor(lo * 10**4))
    return steps


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="kernel/util/sincpowpoly_data.h")
    ap.add_argument("--jobs", type=int, default=None)
    args = ap.parse_args(argv)

    d0, steps = {p: {} for p in FORMATS}, {p: {} for p in FORMATS}
    with Pool(args.jobs, initializer=_init) as pool:
        for m, s in pool.imap_unordered(row_steps, range(MMAX, 0, -1)):
            sys.stderr.write(f"m={m}\n")
            for p in FORMATS:
                d0[p][m] = s[0][p]
                steps[p][m] = s[1][p]
        last = pool.map(check_point, [(i, MMAX) for i in range(0, GRID, 10)])
        far = pool.map(check_point, [(i, M_CHECK) for i in range(0, GRID, 10)])
    for (i, a), (_, b) in zip(last, far):
        for p in FORMATS:
            if b[p] > a[p]:
                raise SystemExit(
                    f"m={M_CHECK} needs {b[p]} > {a[p]} of row {MMAX} at sigma "
                    f"{sigma_at(i):.2f}, MANT_DIG={p}"
                )

    out = [HEADER]
    for i, p in enumerate(FORMATS):
        out += emit(p, d0[p], steps[p], i == 0)
    out.append("#endif")
    with open(args.out, "w") as f:
        f.write("\n".join(out) + "\n")


def row_steps(m):
    """(degree at sigma 1.1, thresholds) of row m, per format."""
    vals = [degrees(sigma_at(i), m) for i in range(GRID)]
    # The exact degree can dip by one in sigma; the table takes the running
    # maximum so that a lookup never falls short.
    for i in range(1, GRID):
        vals[i] = {p: max(vals[i][p], vals[i - 1][p]) for p in FORMATS}
    for p in FORMATS:
        for i in range(GRID - 1):
            step = vals[i + 1][p] - vals[i][p]
            if step not in (0, 1):
                # Not SystemExit: that kills a Pool worker and hangs the pool.
                raise ValueError(
                    f"m={m} MANT_DIG={p}: degree steps by {step} at sigma "
                    f"{sigma_at(i):.2f}"
                )
    return m, ({p: vals[0][p] for p in FORMATS}, thresholds(m, vals))


def check_point(args):
    i, m = args
    return i, degrees(sigma_at(i), m)


if __name__ == "__main__":
    main()
